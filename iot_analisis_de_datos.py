import sqlite3
import pandas as pd

archivos = {
    "100 ms": "iot_100ms.db",
    "500 ms": "iot_500ms.db",
    "1000 ms": "iot_1000ms.db"
}

resumen = []

for nombre, db in archivos.items():

    conn = sqlite3.connect(db)

    df = pd.read_sql_query(
        "SELECT * FROM lecturas_iot ORDER BY id ASC",
        conn
    )

    conn.close()

    df["fecha_registro"] = pd.to_datetime(
        df["fecha_registro"]
    )

    # Frecuencia real
    delta = (
        df["fecha_registro"]
        .diff()
        .dt.total_seconds()
        * 1000
    )

    frecuencia_real = delta.mean()

    # Pérdida de paquetes
    seq_min = df["sequence_id"].min()
    seq_max = df["sequence_id"].max()

    esperados = seq_max - seq_min + 1

    recibidos = len(df)

    perdida = (
        1 - recibidos / esperados
    ) * 100

    resumen.append({
        "Configurada": nombre,
        "Lecturas": len(df),
        "Latencia Media": round(df["latencia"].mean(),2),
        "Latencia Max": round(df["latencia"].max(),2),
        "Frecuencia Real": round(frecuencia_real,2),
        "Paquetes Perdidos (%)": round(perdida,2)
    })

tabla = pd.DataFrame(resumen)

display(tabla)